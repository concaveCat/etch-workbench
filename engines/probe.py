"""Common probe lattice and cross-engine occupancy metrics.

SPX has no grid and ViennaPS has no analytic surface, so "point by point" only
means something on a lattice both engines can answer at: sample the same points in
both, ask each engine which material occupies the point, then compare labels.

The lattice is generated by the scheduler (never by an engine) and shipped inside
the job, so both engines answer exactly the same questions in the same order.

Metrics are deliberately label-based:

* ``agreement``      - fraction of points with the same material (void included);
* ``iou``            - per-material intersection over union;
* ``topHeight``      - highest probed z per material, in um;
* ``disagreement``   - how many points, and the first few coordinates.

No distance transform, no interpolation: a point both engines never sampled is not
a measurement.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Sequence

VOID = "void"


@dataclass(frozen=True)
class Lattice:
    points: list[list[float]]
    shape: tuple[int, int, int]

    def as_json(self) -> dict[str, Any]:
        return {"points": self.points, "shape": list(self.shape)}


def stack_layer_midplanes(job: Any) -> list[float]:
    """z of the middle of every layer the flow will create.

    Thin films (5 nm in Memory1) are invisible to a uniform lattice on a 0.7 um
    window: the probe would report "no such material" on both sides and the
    comparison would silently pass. These mid-planes are added to the lattice so a
    thin layer is actually sampled.
    """
    height = 0.0
    for film in getattr(job.initial, "films", ()) or ():
        height += float(film.thickness)
    mids: list[float] = []
    for step in job.steps[1:]:
        if step.kind == "deposit" and step.mechanism in ("isotropic", "anisotropic"):
            for name, rate in step.rates.items():
                thickness = float(rate) * float(step.duration)
                if thickness > 0:
                    mids.append(height + thickness / 2.0)
                    height += thickness
        elif step.mechanism == "fill":
            offset = float(step.parameters.get("offset", 0.0))
            if offset > 0:
                mids.append(height + offset / 2.0)
                height += offset
    return mids


def build_lattice(width: float, depth: float, below: float, above: float,
                  max_points: int = 20000, extra_z: Sequence[float] = ()) -> Lattice:
    """Regular lattice over ``[0,width] x [0,depth] x [-below, above]``."""
    volume = max(width, 1e-9) * max(depth, 1e-9) * max(below + above, 1e-9)
    step = max((volume / max_points) ** (1 / 3), 1e-4)
    nx = max(2, min(80, int(round(width / step)) + 1))
    ny = max(2, min(80, int(round(depth / step)) + 1))
    nz = max(2, min(120, int(round((below + above) / step)) + 1))
    # Half-offset sampling avoids landing exactly on interfaces, where the
    # "material at a point" question is ill-defined in both engines.
    xs = [(i + 0.5) * width / nx for i in range(nx)]
    ys = [(j + 0.5) * depth / ny for j in range(ny)]
    zs = [-below + (k + 0.5) * (below + above) / nz for k in range(nz)]
    for value in extra_z:
        if -below < float(value) < above:
            zs.append(round(float(value), 6))
    zs = sorted(set(zs))
    points = [[x, y, z] for z in zs for y in ys for x in xs]
    return Lattice(points=points, shape=(nx, ny, nz))


def _top_heights(points: Sequence[Sequence[float]], labels: Sequence[str],
                 materials: Sequence[str]) -> dict[str, float | None]:
    heights: dict[str, float | None] = {}
    for material in materials:
        zs = [points[index][2] for index, value in enumerate(labels) if value == material]
        heights[material] = round(max(zs), 5) if zs else None
    return heights


def occupancy_metrics(points: Sequence[Sequence[float]],
                      left: Sequence[str],
                      right: Sequence[str],
                      left_name: str = "viennaps",
                      right_name: str = "spx") -> dict[str, Any]:
    """Compare two label sequences sampled on the same points."""
    if len(points) != len(left) or len(points) != len(right):
        return {"status": "invalid",
                "reason": f"probe length mismatch: points={len(points)} "
                          f"{left_name}={len(left)} {right_name}={len(right)}"}
    total = len(points)
    if total == 0:
        return {"status": "empty"}
    same = sum(1 for a, b in zip(left, right) if a == b)
    materials = sorted({value for value in list(left) + list(right) if value != VOID})
    iou: dict[str, float] = {}
    for material in materials:
        a = {index for index, value in enumerate(left) if value == material}
        b = {index for index, value in enumerate(right) if value == material}
        union = len(a | b)
        iou[material] = 1.0 if union == 0 else round(len(a & b) / union, 4)
    mismatches = [index for index, (a, b) in enumerate(zip(left, right)) if a != b]
    return {
        "status": "measured",
        "points": total,
        "agreement": round(same / total, 4),
        "iou": iou,
        "mismatchCount": len(mismatches),
        "mismatchExamples": [
            {"point": [round(v, 5) for v in points[index]],
             left_name: left[index], right_name: right[index]}
            for index in mismatches[:5]
        ],
        "topHeightUm": {
            left_name: _top_heights(points, left, materials),
            right_name: _top_heights(points, right, materials),
        },
    }
